import assert from "node:assert/strict";
import test from "node:test";
import { memorySql } from "../helpers/sql";
import { createView } from "../../lib/actions/views";
import { migrate } from "../../lib/actions/migrate";
import { createNote, resolveNote } from "../../lib/actions/notes";
import { parseEvidenceTarget } from "../../lib/actions/evidenceLookup";
import { keepDecision, decisionReviews, verifyDecisionReview } from "../../lib/actions/decisionReview";
import { saveDecision } from "../../lib/actions/viewDecision";
import { listAudit } from "../../lib/actions/audit";
import { evidenceChanged, type CitedFigure } from "../../lib/comparisonDecision";

test("review compares substantive values and keeps missing separate from zero", () => {
  const a = { value:"$1,200,000.00", basis:"Annual  estimate", period:"FY 2025" };
  assert.equal(evidenceChanged(a, { ...a, value:"$ 1.2M", basis:"annual estimate" }), false);
  for (const b of [{ ...a, value:"$1.3M" }, { ...a, basis:"Monthly estimate" }, { ...a, period:"FY 2024" }]) assert.equal(evidenceChanged(a,b), true);
  assert.equal(evidenceChanged({ ...a, value:"—" }, { ...a, value:"0" }), true);
});

test("review scopes, stale writes, independent citations, later evidence and completed requests", async () => {
  const sql = await memorySql();
  await migrate(sql);
  const owner = "reviewer", other = "contributor";
  const common = { name:"Test shortlist", query:"compare=alpha%7Cbravo", ownerId:owner, allowTeam:true };
  const team = await createView(sql,{ ...common, scope:"team" });
  const personal = await createView(sql,{ ...common, scope:"personal" });
  const base: CitedFigure = { targetKind:"site", targetId:"alpha", measure:"power", period:"", basis:"", value:"—" };
  const second = { ...base, targetId:"bravo" };
  const source = parseEvidenceTarget(new URLSearchParams(base)).source;
  const note = await createNote(sql,{ targetKind:"site", targetId:"alpha", authorId:owner, body:"Missing evidence\nCheck the survey." + source }, () => ({}));
  const draft = { preferred:null, rationale:"Wait for the field survey.", citations:[base,second] };
  const { decision } = await saveDecision(sql, team.id, owner, draft, "");
  await saveDecision(sql, personal.id, owner, draft, "");
  const values: Record<string,string> = { alpha:"—", bravo:"—" };
  const load = async () => ({ name:(id:string) => id, figure:(c: typeof base | Omit<typeof base,"value">) => ({ ...c, source:"Survey", value:values[c.targetId] }) });
  const queue = async (who = owner) => (await decisionReviews(sql, who, load)).filter(r => r.reason);
  assert.deepEqual(await queue(), []);
  values.alpha = "Line 420 ft";
  values.bravo = "Line 250 ft";
  assert.equal((await queue()).length, 4);
  const visible = await queue(other);
  assert.ok(visible.every(r => r.view === team.id));
  assert.equal(visible.length, 2);
  const item = visible.find(r => r.site === "alpha")!;
  await assert.rejects(verifyDecisionReview(sql, other, team.id, item.key, item.token, load), /owner/);
  values.alpha = "Line 480 ft";
  await assert.rejects(verifyDecisionReview(sql, owner, team.id, item.key, item.token, load), /changed/);
  const change = (await queue()).find(r => r.view === team.id && r.site === "alpha")!;
  await keepDecision(sql, owner, await verifyDecisionReview(sql,owner,team.id,change.key,change.token,load), decision!.version);
  assert.equal((await queue(other)).length, 1);
  assert.equal((await decisionReviews(sql,other,load,team.id)).find(r=>r.site==="alpha")?.original, "—");
  await assert.rejects(verifyDecisionReview(sql,owner,team.id,change.key,change.token,load), /changed/);
  values.alpha = "LINE 480.0 ft";
  assert.equal((await queue(other)).length, 1);
  await resolveNote(sql,{ id:note.id, actorId:owner });
  const closed = (await queue(other)).find(r=>r.site==="alpha")!;
  assert.equal(closed.reason, "Follow-up completed");
  await keepDecision(sql,owner,await verifyDecisionReview(sql,owner,team.id,closed.key,closed.token,load),decision!.version);
  values.alpha = "—";
  const later = (await queue(other)).find(r=>r.site==="alpha")!;
  assert.equal(later.reason, "Figure changed");
  assert.equal(later.previous.value, "LINE 480.0 ft");
  await saveDecision(sql, team.id, owner, { ...draft, preferred:"bravo", citations:[{ ...second, value:values.bravo }] }, decision!.version);
  assert.deepEqual(await queue(other), []);
  assert.ok((await listAudit(sql)).every(e=>!e.action.startsWith("view.decision")));
});
